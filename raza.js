// Rows that WPA publishes as a single combined class, and the individual
// classes that resolve to them. Note that WPA is not consistent in its own
// files - High Jump uses 'T43/44' for men and 'T43-44' for women.
const COMBINED = {
    'T45-47': ['T45', 'T46', 'T47'],
    'T53/54': ['T53', 'T54'],
    'T43/44': ['T43', 'T44'],
    'T43-44': ['T43', 'T44'],
    'F43/44': ['F43', 'F44']
};

// Accept the spellings people actually type.
const EVENT_ALIASES = {
    '100 m': '100m', '200 m': '200m', '400 m': '400m', '800 m': '800m',
    '1500 m': '1500m', '5000 m': '5000m', '10000 m': '10000m',
    '10,000m': '10000m', '5,000m': '5000m', '1,500m': '1500m',
    'shot': 'Shot Put', 'shotput': 'Shot Put', 'shot put': 'Shot Put',
    'discus throw': 'Discus', 'javelin throw': 'Javelin',
    'club': 'Club Throw', 'club throw': 'Club Throw',
    'long jump': 'Long Jump', 'high jump': 'High Jump',
    'triple jump': 'Triple Jump'
};

function canonicalEvent(discipline) {
    if (!discipline) return null;
    const raw = String(discipline).trim();
    if (TRACK[raw] || FIELD[raw]) return raw;
    const key = raw.toLowerCase();
    if (EVENT_ALIASES[key]) return EVENT_ALIASES[key];
    if (EVENT_ALIASES[raw]) return EVENT_ALIASES[raw];
    const squashed = raw.replace(/\s+/g, '');
    if (TRACK[squashed] || FIELD[squashed]) return squashed;
    return null;
}

function isTrackEvent(d) { const e = canonicalEvent(d); return !!(e && TRACK[e]); }
function isFieldEvent(d) { const e = canonicalEvent(d); return !!(e && FIELD[e]); }

function normaliseSex(sex) {
    const s = String(sex || '').trim().toUpperCase();
    return (s === 'F' || s === 'W' || s.startsWith('WOM') || s === 'FEMALE') ? 'W' : 'M';
}

/**
 * Find the table row for this class, discipline and sex.
 * Handles combined rows (T46 -> T45-47), WPA's inconsistent labels
 * (T43/44 vs T43-44), and mixed-up prefixes (F44 entered for a long jump,
 * which the table keys on T classes).
 */
function resolveClass(event, classCode, sex) {
    const table = TRACK[event] ? TRACK : (FIELD[event] ? FIELD : null);
    if (!table || !classCode) return null;
    const rows = table[event];
    const sx = normaliseSex(sex);

    const raw = String(classCode).trim().toUpperCase();
    if (rows[raw] && rows[raw][sx]) return raw;

    const digits = raw.replace(/[^0-9]/g, '');
    if (!digits) return null;

    for (const prefix of ['T', 'F']) {
        const candidate = prefix + digits;
        if (rows[candidate] && rows[candidate][sx]) return candidate;
        for (const [combined, members] of Object.entries(COMBINED)) {
            if (members.includes(candidate) && rows[combined] && rows[combined][sx]) return combined;
        }
    }
    return null;
}

/**
 * Convert a mark as typed into a number the formula can use.
 * Track: seconds. Accepts "11.10", "2:05.43", "1:02:33.5".
 * Field: metres. Accepts "12.50".
 * Returns null for DNS/DNF/DQ/NM/x and anything unparseable.
 */
function parseMark(mark, forTrack) {
    if (mark === null || mark === undefined) return null;
    const s = String(mark).trim();
    if (!s) return null;
    if (/^(DNS|DNF|DQ|NM|X|-|\u2013)$/i.test(s)) return null;

    if (forTrack && s.includes(':')) {
        const parts = s.split(':').map(Number);
        if (parts.some(isNaN)) return null;
        let seconds = 0;
        for (const part of parts) seconds = seconds * 60 + part;
        return seconds > 0 ? seconds : null;
    }
    const value = parseFloat(s);
    return (isNaN(value) || value <= 0) ? null : value;
}

/**
 * Calculate Raza points for one performance.
 *
 * @returns {{points:number|null, reason?:string, b?:number, c?:number,
 *            classUsed?:string, event?:string, type?:string, pRef?:number}}
 */
function razaPoints(opts) {
    const { classCode, sex, mark, youth = false } = opts || {};
    const event = canonicalEvent(opts && opts.discipline);
    if (!event) return { points: null, reason: 'no Raza table for this discipline' };

    const track = !!TRACK[event];
    const key = resolveClass(event, classCode, sex);
    if (!key) {
        return { points: null, reason: `no published constants for ${classCode} in ${event} (this sex)` };
    }

    const row = (track ? TRACK : FIELD)[event][key][normaliseSex(sex)];
    const b = row[0];
    let c = row[1];

    const p = parseMark(mark, track);
    if (p === null) return { points: null, reason: 'no valid performance' };

    if (youth) c = track ? 1.16 * c : c / 0.88;

    const q = A * Math.exp(-Math.exp(track ? (b - c / p) : (b - c * p)));

    let points = Math.floor(q); // WPA rounds points down
    if (!isFinite(points) || points < 0) points = 0;
    if (points > A) points = A;

    return { points, b, c, classUsed: key, event, type: track ? 'track' : 'field', pRef: row[2] };
}

/**
 * Inverse: the performance required for a given points total.
 * Applies WPA's rounding - distances up to 0.01 m, times down to 0.01 s.
 * Returns null if the points are unreachable (>= 1200) or the row is absent.
 */
function performanceForPoints(opts) {
    const { classCode, sex, points, youth = false } = opts || {};
    const event = canonicalEvent(opts && opts.discipline);
    if (!event || !(points > 0) || points >= A) return null;

    const track = !!TRACK[event];
    const key = resolveClass(event, classCode, sex);
    if (!key) return null;

    const row = (track ? TRACK : FIELD)[event][key][normaliseSex(sex)];
    const b = row[0];
    let c = row[1];
    if (youth) c = track ? 1.16 * c : c / 0.88;

    const inner = b - Math.log(Math.log(A / points));
    if (inner <= 0) return null;

    return track
        ? Math.floor((c / inner) * 100) / 100    // faster time required
        : Math.ceil((inner / c) * 100) / 100;    // longer distance required
}

/** WPA reference performance for a class (roughly the 1000-point mark). */
function referencePerformance(discipline, classCode, sex) {
    const event = canonicalEvent(discipline);
    if (!event) return null;
    const key = resolveClass(event, classCode, sex);
    if (!key) return null;
    return (TRACK[event] ? TRACK : FIELD)[event][key][normaliseSex(sex)][2];
}

/** Every class published for a discipline and sex - handy for dropdowns. */
function classesFor(discipline, sex) {
    const event = canonicalEvent(discipline);
    if (!event) return [];
    const rows = (TRACK[event] ? TRACK : FIELD)[event];
    const sx = normaliseSex(sex);
    return Object.keys(rows).filter(k => rows[k][sx]);
}

